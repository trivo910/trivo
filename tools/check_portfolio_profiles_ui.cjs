// Run only against the isolated SQLite fixture created by the portfolio QA setup.
const { chromium } = require('../.audit/browser-qa/node_modules/playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const directory = path.resolve(__dirname, '../.audit/portfolio-reference');
const credentials = JSON.parse(fs.readFileSync(path.join(directory, 'credentials.json'), 'utf8'));
const origin = 'http://127.0.0.1:18766';
assert.equal(credentials.email, 'portfolio-browser@example.test', 'Use the isolated portfolio fixture');
const admin = `${origin}/${credentials.admin_path}`;
const results = [];

(async () => {
    const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    try {
        for (const mode of ['desktop-light', 'mobile-light', 'desktop-dark']) {
            const context = await browser.newContext({ viewport: { width: mode.startsWith('mobile') ? 390 : 1440, height: 1000 }, colorScheme: mode.endsWith('dark') ? 'dark' : 'light' });
            const page = await context.newPage();
            page.setDefaultTimeout(15000);
            const errors = [];
            page.on('pageerror', error => errors.push(error.message));
            const title = `Synthetic profile ${mode} ${Date.now()}`;
            const profilePath = `/qa-profile-${mode}-${Date.now()}`;
            const headings = () => page.getByLabel('Section heading', { exact: true });
            const bodies = () => page.getByLabel('Section text', { exact: true });
            const save = async (published = false) => {
                await page.getByRole('button', { name: published ? 'Save published portfolio' : 'Save portfolio draft', exact: true }).click();
                await page.waitForLoadState('networkidle');
                await page.getByRole('status').filter({ hasText: published ? 'Published portfolio updated.' : /Portfolio draft (created|saved)\./ }).waitFor();
            };
            await page.goto(`${admin}/login`);
            await page.getByLabel('Email address').fill(credentials.email);
            await page.getByLabel('Password', { exact: true }).fill(credentials.password);
            await page.getByRole('button', { name: 'Sign in', exact: true }).click();
            await page.waitForURL(admin);
            await page.getByLabel('Theme', { exact: true }).selectOption(mode.endsWith('dark') ? 'dark' : 'light');
            await page.getByRole('button', { name: 'Apply', exact: true }).click();
            await page.waitForURL(admin);
            await page.goto(`${admin}/portfolio`);
            await page.getByRole('link', { name: 'Create portfolio draft', exact: true }).click();
            await page.getByLabel('Portfolio title', { exact: true }).fill(title);
            await page.getByLabel('Full portfolio path', { exact: true }).fill(profilePath);
            await page.getByLabel('Display order', { exact: true }).fill('8');
            assert.equal(await headings().count(), 4, 'New profiles must use the visual case-study editor');
            await headings().first().fill(`${title} hero`);
            await bodies().first().fill('<p>Original project introduction.</p>');
            await headings().nth(1).fill('Original project report');
            await bodies().nth(1).fill('<p>Original project report text.</p>');
            const thumbnail = page.getByLabel('Portfolio card thumbnail', { exact: true });
            const imageId = await thumbnail.locator('option').nth(1).getAttribute('value');
            await thumbnail.selectOption(imageId);
            await page.getByLabel('Section image', { exact: true }).first().selectOption(imageId);
            await page.getByRole('button', { name: 'Add card', exact: true }).click();
            await page.getByLabel('Value / project title', { exact: true }).fill('120%');
            await page.getByLabel('Label / display date', { exact: true }).fill('Measured growth');
            await page.getByRole('button', { name: 'Add section', exact: true }).click();
            await headings().last().fill('Additional report');
            await bodies().last().fill('Additional report text.');
            await save();
            const editUrl = page.url();
            assert.match(editUrl, /\/portfolio\/\d+\/edit$/);
            await page.goto(`${admin}/portfolio`);
            await page.getByRole('link', { name: title, exact: true }).click();
            assert.equal(await headings().count(), 5);
            assert.equal(await headings().last().inputValue(), 'Additional report');
            assert.equal(await page.getByLabel('Value / project title', { exact: true }).inputValue(), '120%');
            await page.getByRole('button', { name: 'Move section 3 up', exact: true }).click();
            await page.getByLabel('Portfolio title', { exact: true }).fill(`${title} edited`);
            await headings().nth(2).fill('Edited report');
            await bodies().nth(2).fill('<p>Edited project report text.</p>');
            await page.getByLabel('Button URL', { exact: true }).first().fill('javascript:alert(1)');
            await page.getByRole('button', { name: 'Save portfolio draft', exact: true }).click();
            await page.getByText('Use an internal path or a secure HTTPS URL.', { exact: true }).waitFor();
            assert.equal(await headings().nth(2).inputValue(), 'Edited report', 'Validation must retain edits');
            await page.getByLabel('Button URL', { exact: true }).first().fill('');
            await save();
            await page.reload();
            assert.equal(await headings().nth(1).inputValue(), 'Results');
            assert.equal(await headings().nth(2).inputValue(), 'Edited report');
            assert.equal(await page.getByLabel('Portfolio title', { exact: true }).inputValue(), `${title} edited`);
            const stale = await context.newPage();
            await stale.goto(editUrl);
            await page.getByLabel('Display order', { exact: true }).fill('6');
            await save();
            await stale.getByLabel('Portfolio title', { exact: true }).fill('Stale replacement');
            await stale.getByRole('button', { name: 'Save portfolio draft', exact: true }).click();
            await stale.getByText('This content changed. Reload before saving.', { exact: true }).waitFor();
            await stale.close();
            await page.reload();
            assert.equal(await page.getByLabel('Portfolio title', { exact: true }).inputValue(), `${title} edited`);
            await page.getByRole('link', { name: 'Edit portfolio SEO', exact: true }).click();
            await page.getByLabel('SEO title', { exact: true }).fill('Synthetic portfolio SEO title');
            await page.getByLabel('Meta description', { exact: true }).fill('Synthetic project profile description for browser verification.');
            await page.getByLabel('Robots directives', { exact: true }).fill('index,follow');
            await page.getByRole('button', { name: 'Save portfolio SEO', exact: true }).click();
            await page.getByRole('status').filter({ hasText: 'Portfolio SEO saved.' }).waitFor();
            await page.getByRole('link', { name: 'Back to portfolio', exact: true }).click();
            await page.getByRole('button', { name: 'Publish now', exact: true }).click();
            await page.getByRole('status').filter({ hasText: 'Publication state updated.' }).waitFor();
            await page.getByRole('button', { name: 'Save published portfolio', exact: true }).waitFor();
            await bodies().nth(2).fill('<p>Published edit verified.</p>');
            await save(true);
            await page.reload();
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Admin overflow');
            await page.screenshot({ path: path.join(directory, `profiles-admin-${mode}.png`) });
            await page.goto(`${origin}${profilePath}`);
            await page.getByRole('heading', { name: `${title} hero`, exact: true }).waitFor();
            await page.getByText('Published edit verified.', { exact: true }).waitFor();
            await page.getByText('120%', { exact: true }).waitFor();
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Public overflow');
            await page.goto(`${origin}/portfolio`);
            await page.getByRole('heading', { name: `${title} edited`, exact: true }).waitFor();
            assert.deepEqual(errors, [], 'JavaScript errors');
            results.push({ mode, create: true, reopen: true, edit: true, addSectionAndCard: true, reorder: true, validationPreservesInput: true, staleEditRejected: true, publish: true, publishedEditVisible: true, listingVisible: true, overflow: false, errors });
            await context.close();
        }
        console.log(JSON.stringify(results));
    } finally {
        fs.writeFileSync(path.join(directory, 'profiles-results.json'), JSON.stringify(results, null, 2));
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
